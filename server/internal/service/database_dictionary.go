func enrichDatabaseTableComments(tables []repository.DatabaseTable) {
	for index := range tables {
		if tables[index].Comment == "" {
			tables[index].Comment = databaseTableComments[tables[index].Name]
		}
	}
}

func enrichDatabaseColumnComments(columns []repository.DatabaseColumn) {
	for index := range columns {
		if columns[index].Comment == "" {
			columns[index].Comment = databaseColumnComments[columns[index].Name]
		}
	}
}
